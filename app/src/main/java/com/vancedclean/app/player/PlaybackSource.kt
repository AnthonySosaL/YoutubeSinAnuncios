package com.vancedclean.app.player

import org.schabi.newpipe.extractor.MediaFormat
import org.schabi.newpipe.extractor.stream.AudioStream
import org.schabi.newpipe.extractor.stream.StreamInfo
import org.schabi.newpipe.extractor.stream.VideoStream

/** Una calidad elegible: video (y audio aparte si el video viene sin sonido). */
data class QualityOption(
    val label: String,
    val height: Int,
    val videoUrl: String,
    val audioUrl: String?,
)

data class SubtitleOption(
    val label: String,
    val language: String,
    val url: String,
    val mimeType: String,
)

/** Todo lo necesario para reproducir un video y cambiar calidad/subtítulos. */
data class PlaybackSource(
    val qualities: List<QualityOption>,
    val hlsUrl: String?,
    val subtitles: List<SubtitleOption>,
    val isLive: Boolean,
) {
    val isEmpty get() = qualities.isEmpty() && hlsUrl.isNullOrBlank()

    /** Calidad según el ajuste: "auto" = 720p o la más cercana por debajo. */
    fun pick(preference: String): QualityOption? {
        if (qualities.isEmpty()) return null
        val wanted = preference.takeWhile { it.isDigit() }.toIntOrNull() ?: 720
        return qualities.filter { it.height <= wanted }.maxByOrNull { it.height }
            ?: qualities.minByOrNull { it.height }
    }

    companion object {
        fun from(info: StreamInfo): PlaybackSource {
            val audio = bestAudio(info.audioStreams)
            val adaptive = if (audio == null) emptyList() else info.videoOnlyStreams
                .filter { it.content.isNotBlank() && it.height() > 0 }
                .groupBy { it.height() }
                .mapNotNull { (height, streams) ->
                    val best = streams.sortedWith(compareBy({ codecRank(it) }, { -it.fps })).first()
                    if (codecRank(best) >= 3) return@mapNotNull null
                    QualityOption(label(best), height, best.content, audio.content)
                }
            val muxed = info.videoStreams
                .filter { !it.isVideoOnly && it.content.isNotBlank() }
                .map { QualityOption(label(it), it.height(), it.content, null) }

            // Si una altura existe en ambos, preferimos la que trae el audio integrado.
            val byHeight = (adaptive + muxed).groupBy { it.height }
                .map { (_, opts) -> opts.firstOrNull { it.audioUrl == null } ?: opts.first() }
                .sortedByDescending { it.height }

            // YouTube entrega VTT o TTML según el cliente; el reproductor entiende ambos.
            val subtitles = info.subtitles
                .filter { it.content.isNotBlank() && (it.format == MediaFormat.VTT || it.format == MediaFormat.TTML) }
                .sortedBy { if (it.format == MediaFormat.VTT) 0 else 1 }
                .map {
                    val name = it.displayLanguageName.ifBlank { it.languageTag }
                    SubtitleOption(
                        label = if (it.isAutoGenerated) "$name (automáticos)" else name,
                        language = it.languageTag,
                        url = it.content,
                        mimeType = if (it.format == MediaFormat.VTT) "text/vtt" else "application/ttml+xml",
                    )
                }
                .distinctBy { it.label }
                .sortedWith(compareBy({ !it.language.startsWith("es") }, { it.label }))

            val isLive = info.streamType.name == "LIVE_STREAM" || info.streamType.name == "AUDIO_LIVE_STREAM"
            return PlaybackSource(
                qualities = if (isLive) emptyList() else byHeight,
                hlsUrl = info.hlsUrl?.takeIf { it.isNotBlank() },
                subtitles = subtitles,
                isLive = isLive,
            )
        }

        private fun bestAudio(streams: List<AudioStream>): AudioStream? {
            val usable = streams.filter { it.content.isNotBlank() }
            // Pista original (no doblada) primero, M4A antes que WebM, y la de mayor bitrate.
            return usable.sortedWith(
                compareBy<AudioStream>(
                    { if (it.audioTrackType == null || it.audioTrackType?.name == "ORIGINAL") 0 else 1 },
                    { if (it.format == MediaFormat.M4A) 0 else 1 },
                    { -it.averageBitrate }
                )
            ).firstOrNull()
        }

        /** avc1 es el más compatible; vp9 suele ir bien; av1 se evita (muchos móviles no lo decodifican). */
        private fun codecRank(stream: VideoStream): Int {
            val codec = stream.codec.orEmpty().lowercase()
            return when {
                codec.startsWith("avc") -> 0
                codec.startsWith("vp9") || codec.startsWith("vp09") -> 1
                codec.isBlank() -> if (stream.format == MediaFormat.MPEG_4) 0 else 2
                codec.startsWith("av01") -> 3
                else -> 2
            }
        }

        private fun VideoStream.height(): Int =
            resolution?.takeWhile { it.isDigit() }?.toIntOrNull() ?: 0

        private fun label(stream: VideoStream): String {
            val h = stream.height()
            return if (stream.fps > 30) "${h}p${stream.fps}" else "${h}p"
        }
    }
}
